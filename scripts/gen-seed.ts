// Generates the D1 seed for the built-in exercise library.
// Usage: npm run seed:gen [-- migrations/000X_name.sql]
import { writeFileSync } from 'node:fs';
import { EXERCISES } from '../shared/data/exercises/index.ts';

const out = process.argv[2] ?? 'migrations/0002_seed_exercises.sql';
const q = (s: string) => `'${s.replaceAll("'", "''")}'`;

const rows = EXERCISES.map(
  (x) =>
    `(${[x.id, x.name.en, x.name.de, x.desc.en, x.desc.de, JSON.stringify(x.primary), JSON.stringify(x.secondary), x.equipment, x.tracking, x.category]
      .map(q)
      .join(', ')})`,
);

const header =
  '-- Generated by scripts/gen-seed.ts from shared/data/exercises. Do not edit by hand.\n' +
  '-- Upsert so the seed can be regenerated into a new migration when the library changes.\n';
const chunks: string[] = [];
for (let i = 0; i < rows.length; i += 20) {
  chunks.push(
    'INSERT INTO exercises (id, name_en, name_de, desc_en, desc_de, primary_muscles, secondary_muscles, equipment, tracking, category) VALUES\n' +
      rows.slice(i, i + 20).join(',\n') +
      '\nON CONFLICT(id) DO UPDATE SET name_en = excluded.name_en, name_de = excluded.name_de, desc_en = excluded.desc_en, desc_de = excluded.desc_de,' +
      ' primary_muscles = excluded.primary_muscles, secondary_muscles = excluded.secondary_muscles, equipment = excluded.equipment,' +
      ' tracking = excluded.tracking, category = excluded.category;\n',
  );
}
writeFileSync(out, header + chunks.join('\n'));
console.log(`Wrote ${EXERCISES.length} exercises to ${out}`);
